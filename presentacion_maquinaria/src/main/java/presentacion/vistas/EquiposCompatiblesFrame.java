    private int indice(EquipoDTO equipo, int siNoEsta) {
        if (equipo != null) {
            for (int i = 0; i < compatibles.size(); i++) {
                if (Objects.equals(compatibles.get(i).getIdEquipo(), equipo.getIdEquipo())) {
                    return i;
                }
            }
        }
        return siNoEsta;
    }

